import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "src", "components", "icons.tsx");
const BASE = "https://cdn.jsdelivr.net/npm/@material-symbols/svg-400/sharp";

const ICONS = {
  line: "horizontal_rule",
  rectangle: "rectangle",
  rectangleFilled: "rectangle-fill",
  ellipse: "circle",
  ellipseFilled: "circle-fill",
  shapes: "shapes",
};

const VIEW_BOX = "0 -960 960 960";

async function glyphPath(glyph) {
  const response = await fetch(`${BASE}/${glyph}.svg`);
  if (!response.ok) throw new Error(`${glyph}: HTTP ${response.status}`);
  const svg = await response.text();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (viewBox !== VIEW_BOX) throw new Error(`${glyph}: unexpected viewBox ${viewBox}`);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length !== 1) throw new Error(`${glyph}: expected 1 path, got ${paths.length}`);
  return paths[0];
}

const entries = [];
for (const [name, glyph] of Object.entries(ICONS)) {
  entries.push([name, glyph, await glyphPath(glyph)]);
  process.stdout.write(`.`);
}
process.stdout.write("\n");

const body = entries.map(([name, glyph, path]) => `  /** \`${glyph}\` */\n  ${name}: "${path}",`).join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/fetch-ui-icons.mjs — edit that script, not this file.
// Material Symbols Sharp, weight 400, optical size 24 (Apache License 2.0).
// https://github.com/google/material-design-icons
import type { SVGProps } from "react";

const PATHS = {
${body}
} as const;

export type IconName = keyof typeof PATHS;

/**
 * A single Material Symbols glyph. These are filled paths sitting among
 * hand-drawn stroked icons, so the \`icon\` class is what lets the stylesheet
 * give them \`fill: currentColor\` instead of a stroke — keep it on.
 */
export function Icon({ name, className, ...props }: { name: IconName } & SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="${VIEW_BOX}"
      className={className ? \`icon \${className}\` : "icon"}
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      <path d={PATHS[name]} />
    </svg>
  );
}
`,
);

console.log(`Wrote ${entries.length} icons to ${OUT}`);
